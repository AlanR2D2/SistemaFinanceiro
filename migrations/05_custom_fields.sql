ON CONFLICT (field_id, lower(valor)) DO NOTHING;

-- uf → fin_uf (TABELA COMPARTILHADA — não tem coluna tenant)
-- Insere as opções de UF para cada tenant existente.
INSERT INTO fin_custom_field_options
    (tenant, field_id, valor, cor, cor_letra, hierarquia, ativo, ordem)
SELECT
    f.tenant,
    f.id,
    u.uf,
    NULL,
    '#000000',
    5,
    COALESCE(u.ativo, 1),
    100
FROM fin_uf u
CROSS JOIN fin_custom_fields f
WHERE f.chave = 'uf'
  AND u.uf IS NOT NULL AND u.uf <> ''
ON CONFLICT (field_id, lower(valor)) DO NOTHING;


