ON CONFLICT (field_id, lower(valor)) DO NOTHING;

-- prazo_estimado → fin_prazo_estimado (sem cor/hierarquia)
INSERT INTO fin_custom_field_options
    (tenant, field_id, valor, cor, cor_letra, hierarquia, ativo, ordem)
SELECT
    pe.tenant,
    f.id,
    pe.prazo_estimado,
